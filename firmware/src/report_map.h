// Payload length (without report id) per report id; 0 = unknown id.
static inline int report_len(uint8_t id) {
  switch (id) {
    case 1: return 8;
    case 2: return 4;
    case 3: return 5;
    case 4: return 1;
    default: return 0;
  }
}
